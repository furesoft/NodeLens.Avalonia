using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Runtime.Loader;

using Projectional.Core;
using Projectional.Language;
using Projectional.LanguageExport;
using Projectional.Languages;
using Projectional.Projection;
using Projectional.Persistence;
using Xunit;

namespace Projectional.Core.Tests;

/// <summary>
/// The export as a whole: the files a language becomes, the stub policy, and the assembly the source compiles to.
/// </summary>
/// <remarks>
/// <para>
/// The fixture is the language a user opens - <c>samples/declared-pipeline</c> - because it is the export's first
/// customer: whatever the app can open, the export has to be able to ship.
/// </para>
/// <para>
/// The assembled proof is that the compiled assembly is the same language, not that the compile succeeded. The test
/// loads the bytes the exporter produced, asks the loaded type for its declarations, and compares the registry they
/// build against the one the folder built - the same dump <c>ParityHarness</c> uses for the two authoring paths.
/// </para>
/// </summary>
public sealed class LanguageExporterTests
{
    /// <summary>The assemblies <c>Projectional.Toolkit</c> brings, which is everything an exported language may name.</summary>
    private static readonly string[] ToolkitAssemblies = ["Projectional.Core", "Projectional.Language"];
    [Fact]
    public void TheDeclaredSampleExportsAsALanguageClass()
    {
        var language = Declared();

        var result = LanguageExporter.Export(language, "Sample.Language");

        Assert.Equal(["DeclaredLanguage.cs", "README.md"], result.Files.Select(file => file.Name));
        Assert.Null(result.Assembly);

        Assert.Equal(
            """
            // <auto-generated>
            //     Generated from the declared language 'Declared'.
            //     Edit the definitions, not this file: the next export replaces it.
            // </auto-generated>

            using System;
            using System.Collections.Generic;

            using Projectional.Core;
            using Projectional.Language;

            namespace Sample.Language;

            /// <summary>The language <c>Declared</c> declares, as C#.</summary>
            public static class DeclaredLanguage
            {
                public static IReadOnlyList<ConceptDeclaration> ConceptDeclarations { get; } =
                [
                    new ConceptDeclaration(
                        "Pipeline.Pipeline",
                        [
                            new PropertySlot("name", PropertyType.String, "unnamed"),
                            new ChildSlot("stages", "Pipeline.Stage", Cardinality.Many, minimum: 1),
                        ],
                        interfaces: ["Framework.Named"],
                        description: "A named sequence of stages."
                    ),
                    new ConceptDeclaration(
                        "Pipeline.Stage",
                        [
                            new PropertySlot("name", PropertyType.String, "unnamed"),
                            new PropertySlot("command", PropertyType.String),
                            new PropertySlot("retries", PropertyType.Integer, "0"),
                        ],
                        interfaces: ["Framework.Named"],
                        description: "One step of a pipeline."
                    ),
                ];

                /// <summary>How those concepts are drawn.</summary>
                public static NotationRegistry CreateNotations(ConceptRegistry concepts)
                {
                    var notations = new NotationRegistry(concepts);

                    notations.Add("Pipeline.Pipeline", ed => ed.Sequence(
                        ed.Line(ed.Keyword("pipeline"), ed.Space, ed.Property("name")),
                        ed.Indent(
                            ed.Table("stages", "+ stage", ed.Column("name", ed.Keyword("stage")), ed.Column("command", ed.Keyword("run")), ed.Column("retries", ed.Keyword("retries")))
                        )
                    ));
                    notations.Add("Pipeline.Stage", ed => ed.Line(ed.Property("name"), ed.Space, ed.Property("command"), ed.Space, ed.Property("retries")));

                    return notations;
                }

                /// <summary>The declared text generators, which this export cannot write yet.</summary>
                public static IReadOnlyList<TextGenerator> Generators =>
                    throw new NotSupportedException("The text generators declared in 'generator' have no export spelling yet; write them in this project's `Checks/` or `Intentions/` folder.");
            }

            """,
            result.Files[0].Text,
            ignoreLineEndingDifferences: true);
    }

    [Fact]
    public void TheReadmeSaysWhatTheExportCouldNotWrite()
    {
        // The sample declares constraints and a generator, so the README has to name both - and say why a constraint
        // cannot even be stubbed while a generator can.
        var readme = LanguageExporter.Export(Declared(), "Sample.Language").Files[1].Text;

        Assert.Contains("| `constraints/` |", readme, StringComparison.Ordinal);
        Assert.Contains("| `generator/` |", readme, StringComparison.Ordinal);
        Assert.Contains("`Generators`", readme, StringComparison.Ordinal);
        Assert.DoesNotContain("| `types/` |", readme, StringComparison.Ordinal);
        Assert.DoesNotContain("`Types`", readme, StringComparison.Ordinal);
        Assert.Contains("These cannot be stubbed", readme, StringComparison.Ordinal);
    }

    [Fact]
    public void AScopeRuleAnIntentionAndAConstraintAreAllNamedAsOmitted()
    {
        // The export writes declarations and notation; everything that is behaviour is named rather than dropped,
        // and none of the three can be a stub - the toolkit does not carry the assemblies they live in.
        var readme = LanguageExporter.Export(
            "Board",
            [new ConceptDeclaration("Board.Card")],
            [],
            hasConstraints: true,
            hasScopes: true,
            hasIntentions: true).Files[1].Text;

        Assert.Contains("| `constraints/` |", readme, StringComparison.Ordinal);
        Assert.Contains("| `scopes/` |", readme, StringComparison.Ordinal);
        Assert.Contains("| `intentions/` |", readme, StringComparison.Ordinal);

        // No stub is emitted for any of them, so the README does not claim one.
        Assert.DoesNotContain("`Types`", readme, StringComparison.Ordinal);
        Assert.Contains("These cannot be stubbed", readme, StringComparison.Ordinal);
    }

    [Fact]
    public void ALanguageWithNothingOmittedSaysSo()
    {
        var result = LanguageExporter.Export("Board", [new ConceptDeclaration("Board.Card")], []);

        Assert.Contains(
            "Nothing. Every aspect this language declares is in the generated file.",
            result.Files[1].Text,
            StringComparison.Ordinal);
    }

    [Fact]
    public void AnAspectTheExportCannotWriteThrowsInsteadOfAnsweringAnEmptyRegistry()
    {
        var result = LanguageExporter.Export(
            "Declared",
            [],
            [],
            hasTypes: true,
            hasGenerators: true,
            hasConstraints: true);

        var source = result.Files[0].Text;

        Assert.Contains("public static TypeRegistry Types =>", source, StringComparison.Ordinal);
        Assert.Contains("public static IReadOnlyList<TextGenerator> Generators =>", source, StringComparison.Ordinal);
        Assert.Contains("throw new NotSupportedException(\"The type rules declared in 'types'", source, StringComparison.Ordinal);
        Assert.Contains("throw new NotSupportedException(\"The text generators declared in 'generator'", source, StringComparison.Ordinal);

        // A constraint is left out of the file entirely: a `ConstraintSet` cannot be named through the toolkit.
        Assert.DoesNotContain("Constraints =>", source, StringComparison.Ordinal);
    }

    [Fact]
    public void AskingForTheAssemblyCompilesTheSourceItJustWrote()
    {
        var result = LanguageExporter.Export(Declared(), "Sample.Language", ExportOutput.Assembly);

        Assert.NotNull(result.Assembly);
        Assert.Equal("DeclaredLanguage.dll", result.Assembly.Name);
        Assert.True(result.Assembly.Bytes.Length > 0);

        // A PE image starts with "MZ": the bytes are an assembly, not a serialized error.
        Assert.Equal((byte)'M', result.Assembly.Bytes[0]);
        Assert.Equal((byte)'Z', result.Assembly.Bytes[1]);

        // The source is still there: the assembly is added to what the exporter answers, never a replacement.
        Assert.Equal("DeclaredLanguage.cs", result.Files[0].Name);
    }

    [Fact]
    public void TheCompiledAssemblyDeclaresTheSameLanguageAsTheFolder()
    {
        var language = Declared();
        var result = LanguageExporter.Export(language, "Sample.Language", ExportOutput.Assembly);

        var assembly = AssemblyLoadContext.Default.LoadFromStream(new MemoryStream(result.Assembly!.Bytes));
        var type = assembly.GetType("Sample.Language.DeclaredLanguage", throwOnError: true);

        Assert.NotNull(type);

        var exported = (IReadOnlyList<ConceptDeclaration>)type
            .GetProperty("ConceptDeclarations", BindingFlags.Public | BindingFlags.Static)!
            .GetValue(null)!;

        // The declarations build the registry the folder built: same concepts, same order, same slots.
        Assert.Equal(ParityHarness.Dump(language.Concepts), ParityHarness.Dump(ConceptRegistry.Create(exported)));

        // And the notation draws the same document the same way, which is the half a registry dump cannot see.
        var createNotations = type.GetMethod("CreateNotations", BindingFlags.Public | BindingFlags.Static);

        Assert.NotNull(createNotations);

        var notations = (NotationRegistry)createNotations.Invoke(null, [ConceptRegistry.Create(exported)])!;
        var model = ModelFile.Load(language.NewProject(), Path.Combine(AppContext.BaseDirectory, "Declared", "pipeline.mps"));

        Assert.Equal(
            LayoutSnapshot.Render(model, language.Notations, width: 60),
            LayoutSnapshot.Render(model, notations, width: 60));
    }

    [Fact]
    public void TheCompiledAssemblyNeedsNothingTheToolkitDoesNotBring()
    {
        // ADR 0019: a language package references the toolkit and nothing else. An exported language that needed
        // more would not be shippable that way, so the promise is read back off the emitted metadata.
        var result = LanguageExporter.Export(Declared(), "Sample.Language", ExportOutput.Assembly);

        using var stream = new MemoryStream(result.Assembly!.Bytes);
        using var reader = new PEReader(stream);
        var metadata = reader.GetMetadataReader();

        var references = metadata.AssemblyReferences
            .Select(handle => metadata.GetString(metadata.GetAssemblyReference(handle).Name))
            .Where(name => name.StartsWith("Projectional.", StringComparison.Ordinal))
            .ToArray();

        Assert.All(references, name => Assert.Contains(name, ToolkitAssemblies));
    }

    [Fact]
    public void TheSameLanguageCompilesToTheSameBytes()
    {
        // Deterministic emission is what lets an exported package be checked in, cached or compared.
        var language = Declared();

        var first = LanguageExporter.Export(language, "Sample.Language", ExportOutput.Assembly).Assembly!;
        var second = LanguageExporter.Export(language, "Sample.Language", ExportOutput.Assembly).Assembly!;

        Assert.Equal(first.Bytes, second.Bytes);
    }

    private static LanguageProject Declared()
    {
        var language = LanguageProject.Open(Path.Combine(AppContext.BaseDirectory, "Declared"), out var error);

        Assert.Null(error);
        Assert.NotNull(language);

        return language;
    }
}
