    [Fact]
    public void TheCompiledAssemblyStatesTheRootsIdentity()
    {
        // Read back off the binary, not off the source: the point of an attribute is that it survives the compile.
        var result = LanguageExporter.Export(Declared(), "Sample.Language", ExportOutput.Assembly);

        var assembly = AssemblyLoadContext.Default.LoadFromStream(new MemoryStream(result.Assembly!.Bytes));

        var metadata = assembly
            .GetCustomAttributes<AssemblyMetadataAttribute>()
            .ToDictionary(attribute => attribute.Key, attribute => attribute.Value, StringComparer.Ordinal);

        Assert.Equal("Pipeline", metadata[LanguageExporter.LanguageKey]);
        Assert.Equal("1.0.0", metadata[LanguageExporter.VersionKey]);
        Assert.Equal(
            "1.0.0",
            assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()!.InformationalVersion);
    }

    [Fact]
    public void ADependentLanguageExportsOnePackagePerLanguageItStandsOn()
    {
        // declared-invoice extends Units, and a folder holding only the dependent's file would be a package whose base
        // the caller has to find elsewhere. Base first, because that is the order a consumer installs in, and the
        // single `Assembly` is the language that was asked for - the last one.
        var result = LanguageExporter.Export(Invoice(), "Sample.Invoice", ExportOutput.Assembly);

        Assert.Equal(["UnitsLanguage-1.0.0.cs", "InvoiceLanguage-1.0.0.cs", "README.md"], result.Files.Select(file => file.Name));
        Assert.Equal(["UnitsLanguage-1.0.0.dll", "InvoiceLanguage-1.0.0.dll"], result.Assemblies.Select(assembly => assembly.Name));
        Assert.Equal("InvoiceLanguage-1.0.0.dll", result.Assembly!.Name);

        // The base's package says what it is, and the dependent's README names the file beside it.
        var units = AssemblyLoadContext.Default.LoadFromStream(new MemoryStream(result.Assemblies[0].Bytes));
        var metadata = units
            .GetCustomAttributes<AssemblyMetadataAttribute>()
            .ToDictionary(attribute => attribute.Key, attribute => attribute.Value, StringComparer.Ordinal);

        Assert.Equal("Units", metadata[LanguageExporter.LanguageKey]);
        Assert.Contains("UnitsLanguage-1.0.0.cs", result.Files[^1].Text, StringComparison.Ordinal);
    }

    [Fact]
    public void TheWholeChainCanBeOneAssembly()
    {
        // The other layout a caller chooses: one binary holding every language of the export, named after the language
        // that was exported. The files stay one per language - what changes is only what is compiled.
        var result = LanguageExporter.Export(
            Invoice(),
            "Sample.Invoice",
            ExportOutput.Assembly,
            AssemblyLayout.Combined);

        Assert.Equal(["UnitsLanguage-1.0.0.cs", "InvoiceLanguage-1.0.0.cs", "README.md"], result.Files.Select(file => file.Name));

        var assembly = Assert.Single(result.Assemblies);

        Assert.Equal("InvoiceLanguage-1.0.0.dll", assembly.Name);

        var loaded = AssemblyLoadContext.Default.LoadFromStream(new MemoryStream(assembly.Bytes));

        // Both halves are in the one binary, which is the claim a combined layout makes.
        Assert.NotNull(loaded.GetType("Units.UnitsLanguage", throwOnError: false));
        Assert.NotNull(loaded.GetType("Sample.Invoice.InvoiceLanguage", throwOnError: false));

        // One assembly holds one informational version, and it is the exported language's: a dependency keeps its own
        // version as metadata instead - the compile would have refused a second attribute.
        Assert.Equal(
            "1.0.0",
            loaded.GetCustomAttribute<AssemblyInformationalVersionAttribute>()!.InformationalVersion);
    }

