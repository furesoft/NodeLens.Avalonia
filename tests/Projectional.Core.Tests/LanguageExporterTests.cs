/// <summary>
/// The export as a whole: the files a language becomes, the stub policy, and the assembly the source compiles to.
/// </summary>
/// <remarks>
/// <para>
/// The fixture is the language a user opens - <c>samples/declared-pipeline</c> - because it is the export's first
/// customer: whatever the app can open, the export has to be able to ship.
/// </para>
/// <para>
/// The assembled proof is that the compiled assembly is the same language, not that the compile succeeded. The test
