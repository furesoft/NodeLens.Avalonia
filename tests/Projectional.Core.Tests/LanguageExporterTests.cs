    [Fact]
    public void TheCompiledAssemblyDeclaresTheSameLanguageAsTheFolder()
    {
        var language = Declared();
        var result = LanguageExporter.Export(language, "Sample.Language", ExportOutput.Assembly);

        var assembly = AssemblyLoadContext.Default.LoadFromStream(new MemoryStream(result.Assembly!.Bytes));
        var type = assembly.GetType("Sample.Language.PipelineLanguage", throwOnError: true);

        Assert.NotNull(type);

        var exported = (IReadOnlyList<ConceptDeclaration>)type
            .GetProperty("ConceptDeclarations", BindingFlags.Public | BindingFlags.Static)!
            .GetValue(null)!;

        // The declarations build the registry the folder built: same concepts, same order, same slots.
        Assert.Equal(ParityHarness.Dump(language.Concepts), ParityHarness.Dump(ConceptRegistry.Create(exported)));

        // And the notation draws the same document the same way, which is the half a registry dump cannot see.
        var createNotations = type.GetMethod("CreateNotations", BindingFlags.Public | BindingFlags.Static);

        Assert.NotNull(createNotations);

        var notations = (NotationRegistry)createNotations.Invoke(null, [ConceptRegistry.Create(exported)])!;
        var model = ModelFile.Load(language.NewProject(), Path.Combine(AppContext.BaseDirectory, "Declared", "pipeline.mps"));

        Assert.Equal(
            LayoutSnapshot.Render(model, language.Notations, width: 60),
            LayoutSnapshot.Render(model, notations, width: 60));
    }

    [Fact]
    public void TheTypingRulesAreWrittenOutRatherThanNamed()
    {
        // Typing is the one behaviour aspect the export can spell, so a language that declares it gets the rules in
        // the file - and the README must not claim they were left out.
        var language = LanguageProject.Open(Path.Combine(AppContext.BaseDirectory, "Expressions"), out var error);

        Assert.Null(error);
        Assert.NotNull(language);
        Assert.True(language.HasTyping);

        var result = LanguageExporter.Export(language, "Sample.Language");
        var source = result.Files[0].Text;

        Assert.Contains("public static ITypingRules CreateTypingRules()", source, StringComparison.Ordinal);
        Assert.Contains("using System.Linq;", source, StringComparison.Ordinal);

        // `Projectional.Language` and nothing else: `ITypingRules` and `TypingRuleRegistry` live there, and a using of
        // `Projectional.TypingRules` would not compile in a package that references only the toolkit.
        Assert.Contains("using Projectional.Language;", source, StringComparison.Ordinal);
        Assert.DoesNotContain("using Projectional.TypingRules;", source, StringComparison.Ordinal);
        Assert.Contains(
            ".Add(\"Decl.Int\", text => text.All(char.IsAsciiDigit), \"value\")",
            source,
            StringComparison.Ordinal);
        Assert.Contains(
            ".Add(\"Decl.Bool\", text => text is \"true\" or \"false\", \"value\")",
            source,
            StringComparison.Ordinal);

        // The importer is named, because an importer is a rule set in an assembly the toolkit does not carry.
        var readme = result.Files[1].Text;

        Assert.Contains("| `import/` |", readme, StringComparison.Ordinal);
        Assert.DoesNotContain("| `typing/` |", readme, StringComparison.Ordinal);
        Assert.Contains("CreateTypingRules", readme, StringComparison.Ordinal);
    }

    [Fact]
    public void AnAliasClaimIsWrittenAsTheWordItResolvedTo()
    {
        // The rule says "the concept's alias"; the file a package ships has to say the word, because a generated
        // language has no structure document to look it up in.
        var result = LanguageExporter.Export(
            "Declared",
            [new ConceptDeclaration("Doc.Number", [new PropertySlot("value", PropertyType.String)], alias: "num")],
            [],
            typingRules: [new DeclaredTypingRule("Doc.Number", TypingClaims.Alias, "num", "value")]);

        Assert.Contains(
            ".Add(\"Doc.Number\", text => text == \"num\", \"value\")",
            result.Files[0].Text,
            StringComparison.Ordinal);
    }

    [Fact]
    public void AnAliasWithSpacesIsOneWordNotAWordList()
    {
        // An alias may be a phrase - the declaration only refuses whitespace-only - and the folder claims it whole. The
        // export wrote it through the `any of` pattern first, which split it: the generated language claimed `circle`,
        // `with` and `radius` as three separate keystrokes, none of which its folder claimed.
        var result = LanguageExporter.Export(
            "Declared",
            [new ConceptDeclaration("Doc.Shape", [new PropertySlot("name", PropertyType.String)], alias: "circle with radius")],
            [],
            typingRules: [new DeclaredTypingRule("Doc.Shape", TypingClaims.Alias, "circle with radius", "name")]);

        Assert.Contains(
            ".Add(\"Doc.Shape\", text => text == \"circle with radius\", \"name\")",
            result.Files[0].Text,
            StringComparison.Ordinal);

        Assert.DoesNotContain("text is \"circle\"", result.Files[0].Text, StringComparison.Ordinal);
    }

    [Fact]
    public void TheCompiledAssemblyClaimsTheSameTextAsTheFolder()
    {
        // The parity that matters for this aspect is behavioural: the generated registry has to claim the same bursts
        // of typing as the folder did. A generated language that claimed different text would be one whose export
        // cannot be typed into the way its folder could.
        var language = LanguageProject.Open(Path.Combine(AppContext.BaseDirectory, "Expressions"), out var error);

        Assert.Null(error);
        Assert.NotNull(language);

        var result = LanguageExporter.Export(language, "Sample.Language", ExportOutput.Assembly);
        var assembly = AssemblyLoadContext.Default.LoadFromStream(new MemoryStream(result.Assembly!.Bytes));
        var type = assembly.GetType("Sample.Language.ExpressionsLanguage", throwOnError: true);

        Assert.NotNull(type);

        var create = type.GetMethod("CreateTypingRules", BindingFlags.Public | BindingFlags.Static);

        Assert.NotNull(create);

        var exported = (ITypingRules)create.Invoke(null, [])!;

        foreach (var concept in new[] { "Decl.Int", "Decl.Bool", "Decl.Binary", "Decl.If" })
        {
            foreach (var text in new[] { "42", "4x", "true", "false", "TRUE", "@", "\"quoted" })
            {
                Assert.Equal(
                    language.Typing.ClaimFor(concept, text)?.PropertySlot,
                    exported.ClaimFor(concept, text)?.PropertySlot);
            }
        }
    }

